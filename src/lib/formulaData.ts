export function resolveExamPreset(exam: string): ExamPreset {
  const normalized = exam.toLowerCase().trim();
  if (["jee", "jee-main", "jee main", "jee-main+jee-advanced", "jee advanced", "jee-advanced"].includes(normalized)) return "JEE";
  if (["neet"].includes(normalized)) return "NEET";
  if (["cbse", "cbse class 11", "cbse class 12", "class 11", "class 12"].includes(normalized)) return "CBSE";
  if (["olympiad", "physics olympiad", "chemistry olympiad", "math olympiad", "mathematics olympiad"].includes(normalized)) return "Olympiad";
  if (["nda"].includes(normalized)) return "NDA";
  if (["cuet"].includes(normalized)) return "CUET";
  if (["gate"].includes(normalized)) return "GATE";
  if (["ssc", "ssc quant"].includes(normalized)) return "SSC";
  if (["cat", "cat quant"].includes(normalized)) return "CAT";
  if (["commerce"].includes(normalized)) return "Commerce";
  if (["upsc"].includes(normalized)) return "UPSC";
  return "Custom";
}

export function seedFormulasForExam(exam: ExamPreset | string): Formula[] {
  const preset = typeof exam === "string" ? resolveExamPreset(exam) : exam;
  const seeds = ALL_SEEDS[preset] || [];
  return seeds.map(f);
}

