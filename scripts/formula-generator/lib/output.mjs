/**
 * output.mjs
 * -----------------------------------------------------------------------------
 * Output writers. Produces:
 *   - Per-subject TypeScript files (same shape the Formula Vault already reads),
 *     chunked to avoid pathological single-file sizes.
 *   - An index.ts with helpers (same public API as today + new helpers).
 *   - A full nested JSON catalog under public/data/formula-catalog.json.
 */

import { writeFileSync, mkdirSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';
import { SCHEMA_VERSION, GENERATOR_NAME } from './constants.mjs';
import { toVarName } from './ids.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));

const CHUNK_SIZE = 800; // formulas per chunk file (tunable)

/** @param {string} path */
function ensureDir(path) {
  mkdirSync(dirname(path), { recursive: true });
}

/**
 * @param {object[]} formulas
 * @param {string} subject
 * @returns {string} TS module source for one chunk
 */
function renderTsChunk(formulas, subject, chunkIndex) {
  const header = `// AUTO-GENERATED by ${GENERATOR_NAME} (schema v${SCHEMA_VERSION}) — DO NOT EDIT MANUALLY
import type { Formula } from '../../types';

/** ${subject} formulas (chunk ${chunkIndex}) */
export const ${toVarName(subject)}Chunk${chunkIndex}: Formula[] = `;
  return header + JSON.stringify(formulas, null, 2) + ';\n';
}

/**
 * Write per-subject TS files. If a subject has more than CHUNK_SIZE formulas,
 * it is split into chunk files and an aggregator barrel re-exports them under
 * the single expected name.
 * @param {object[]} formulas
 * @param {string} subject
 * @param {string} outDir
 * @returns {string[]} written file paths
 */
export function writeSubjectTs(formulas, subject, outDir) {
  const fileStem = subject.toLowerCase().replace(/[^a-z0-9]+/g, '-');
  const written = [];
  if (formulas.length <= CHUNK_SIZE) {
    const path = join(outDir, `${fileStem}.ts`);
    ensureDir(path);
    const varName = toVarName(subject);
    const header = `// AUTO-GENERATED by ${GENERATOR_NAME} (schema v${SCHEMA_VERSION}) — DO NOT EDIT MANUALLY
import type { Formula } from '../../types';

export const ${varName}: Formula[] = `;
    writeFileSync(path, header + JSON.stringify(formulas, null, 2) + ';\n');
    written.push(path);
    return written;
  }

  // Chunked mode
  const chunkFiles = [];
  for (let i = 0; i < formulas.length; i += CHUNK_SIZE) {
    const chunk = formulas.slice(i, i + CHUNK_SIZE);
    const idx = Math.floor(i / CHUNK_SIZE);
    const chunkVar = `${toVarName(subject)}Chunk${idx}`;
    const path = join(outDir, `${fileStem}.chunk-${idx}.ts`);
    ensureDir(path);
    writeFileSync(path, renderTsChunk(chunk, subject, idx));
    chunkFiles.push({ path, var: chunkVar, count: chunk.length });
    written.push(path);
  }
  // Aggregator barrel
  const barrelVar = toVarName(subject);
  const barrelPath = join(outDir, `${fileStem}.ts`);
  ensureDir(barrelPath);
  const imports = chunkFiles.map((c) => `import { ${c.var} } from './${c.path.split(/[\\/]/).pop().replace(/\.ts$/, '')}';`).join('\n');
  const spread = chunkFiles.map((c) => `...${c.var}`).join(',\n  ');
  const barrel = `// AUTO-GENERATED by ${GENERATOR_NAME} (schema v${SCHEMA_VERSION}) — DO NOT EDIT MANUALLY
import type { Formula } from '../../types';
${imports}

export const ${barrelVar}: Formula[] = [
  ${spread},
];
`;
  writeFileSync(barrelPath, barrel);
  written.push(barrelPath);
  return written;
}

/**
 * Write the shared index.ts for src/data/formulas with the same public helpers
 * the Formula Vault already imports, plus new helpers for the expanded model.
 * @param {Array<{ subject: string, varName: string, count: number }>} subjects
 * @param {string} outDir
 * @returns {string}
 */
export function writeIndexTs(subjects, outDir) {
  const path = join(outDir, 'index.ts');
  ensureDir(path);
  const lines = [];
  lines.push(`// AUTO-GENERATED by ${GENERATOR_NAME} (schema v${SCHEMA_VERSION}) — DO NOT EDIT MANUALLY`);
  lines.push(`import type { Formula, FormulaSubject } from '../../types';`);
  for (const s of subjects) {
    lines.push(`import { ${s.varName} } from './${s.subject.toLowerCase().replace(/[^a-z0-9]+/g, '-')}';`);
  }
  lines.push('');
  lines.push(`export const allFormulas: Formula[] = [`);
  for (const s of subjects) {
    lines.push(`  ...${s.varName},`);
  }
  lines.push(`];`);
  lines.push('');
  lines.push(`export { ${subjects.map((s) => s.varName).join(', ')} };`);
  lines.push('');
  lines.push(`export function getFormulaById(id: string): Formula | undefined {`);
  lines.push(`  return allFormulas.find((f) => f.id === id);`);
  lines.push(`}`);
  lines.push('');
  lines.push(`export function getFormulaSubjects(): string[] {`);
  lines.push(`  return [...new Set(allFormulas.map((f) => f.subject))].sort();`);
  lines.push(`}`);
  lines.push('');
  lines.push(`export function getFormulaCategories(subject: FormulaSubject): string[] {`);
  lines.push(`  return [...new Set(allFormulas.filter((f) => f.subject === subject).map((f) => f.category).filter(Boolean))].sort();`);
  lines.push(`}`);
  lines.push('');
  lines.push(`export function getBranchesByCategory(subject: FormulaSubject, category: string): string[] {`);
  lines.push(`  return [...new Set(allFormulas.filter((f) => f.subject === subject && f.category === category).map((f) => f.branch).filter((b): b is string => Boolean(b)))].sort();`);
  lines.push(`}`);
  lines.push('');
  lines.push(`export function getChaptersByCategory(subject: FormulaSubject, category: string): string[] {`);
  lines.push(`  return [...new Set(allFormulas.filter((f) => f.subject === subject && f.category === category).map((f) => f.chapter))].sort((a, b) => a.localeCompare(b));`);
  lines.push(`}`);
  lines.push('');
  lines.push(`export function getFormulasByExam(examId: string): Formula[] {`);
  lines.push(`  return allFormulas.filter((f) => (f.exams || []).includes(examId));`);
  lines.push(`}`);
  writeFileSync(path, lines.join('\n') + '\n');
  return path;
}

/**
 * Build the nested JSON catalog: { meta, exams, subjects, chapters, formulas }.
 * @param {object[]} formulas
 * @param {object} meta
 * @param {string} outPath
 */
export function writeJsonCatalog(formulas, meta, outPath) {
  const byExam = new Map();
  const bySubject = new Map();
  const byBranch = new Map();
  const byChapter = new Map();
  for (const f of formulas) {
    for (const exam of f.exams || []) {
      if (!byExam.has(exam)) byExam.set(exam, []);
      byExam.get(exam).push(f.id);
    }
    const sk = f.subject;
    if (!bySubject.has(sk)) bySubject.set(sk, []);
    bySubject.get(sk).push(f.id);
    const bk = `${f.subject}||${f.branch || ''}`;
    if (!byBranch.has(bk)) byBranch.set(bk, []);
    byBranch.get(bk).push(f.id);
    const ck = `${f.subject}||${f.branch || ''}||${f.chapter}`;
    if (!byChapter.has(ck)) byChapter.set(ck, []);
    byChapter.get(ck).push(f.id);
  }
  const catalog = {
    $schema: './formula-catalog.schema.json',
    meta: {
      ...meta,
      schemaVersion: SCHEMA_VERSION,
      generatedBy: GENERATOR_NAME,
      generatedAt: new Date().toISOString(),
      totalFormulas: formulas.length,
    },
    exams: [...byExam.entries()].map(([id, formulaIds]) => ({ id, formulaIds })),
    subjects: [...bySubject.entries()].map(([name, formulaIds]) => ({ name, formulaIds })),
    branches: [...byBranch.entries()].map(([key, formulaIds]) => {
      const [subject, branch] = key.split('||');
      return { subject, branch, formulaIds };
    }),
    chapters: [...byChapter.entries()].map(([key, formulaIds]) => {
      const [subject, branch, chapter] = key.split('||');
      return { subject, branch, chapter, formulaIds };
    }),
    formulas,
  };
  ensureDir(outPath);
  writeFileSync(outPath, JSON.stringify(catalog, null, 2) + '\n');
  return outPath;
}

